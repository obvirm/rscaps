const clickByText = async (sel, text) => {
  const ok = await p.evaluate((sel, text) => {
    const el = [...document.querySelectorAll(sel)].find((e) => e.textContent.trim().includes(text));
    if (el) el.click();
    return !!el;
  }, sel, text);
  if (!ok) throw new Error(`not found: ${sel} "${text}"`);
};
