/// Signature every native template renderer shares.
pub type RenderFn = for<'a, 'b> fn(&CaptionDocument, f32, &FFramesContext<'a, 'b>) -> Svgr<'a>;

/// One native template, as loaded from `src/templates/<id>/` by build.rs.
///
/// `id` = folder name (also the `doc.template` value and the `render` fn
/// path), `label`/`category`/`gallery_order` come from that folder's
/// `template.json`. Never edit a list by hand — add a folder instead.
pub struct TemplateEntry {
    pub id: &'static str,
    pub label: &'static str,
    pub category: &'static str,
    pub gallery_order: Option<u32>,
    pub render: RenderFn,
}

// Generated by build.rs from src/templates/<id>/{mod.rs, template.json}:
// the single REGISTRY that drives both dispatch and the consumer catalog.
include!(concat!(env!("OUT_DIR"), "/template_registry.rs"));

/// The registry: every native template, generated at build time from the
/// template folders. Adding a template = drop a folder + one `pub mod`
/// line in this file; this slice and `template_catalog_json` update
/// themselves.
pub fn template_catalog() -> &'static [TemplateEntry] {
    REGISTRY
}

/// Renders `doc` through the native template identified by `template`.
///
/// Returns `None` for an unknown id so the caller can fall back to the v0
/// renderer, and `Some(Svgr::empty())` when the id is known but nothing is
/// on screen at `now_ms`.
pub fn render<'a>(
    template: &str,
    doc: &CaptionDocument,
    now_ms: f32,
    ctx: &FFramesContext<'a, '_>,
) -> Option<Svgr<'a>> {
    REGISTRY
        .iter()
        .find(|entry| entry.id == template)
        .map(|entry| (entry.render)(doc, now_ms, ctx))
}

/// JSON `[{"id": "ada", "label": "Ada", "category": "classic"}, …]` — the
/// template catalog.
///
/// Consumers (studio UIs, other apps) must show this instead of hardcoding
/// their own copy of the id/label list; it is derived from the same
/// `REGISTRY` that drives `render`, so it can never drift. `galleryOrder`
/// is present only on templates that declare one (gallery sorting hint).
pub fn template_catalog_json() -> String {
    let entries: Vec<serde_json::Value> = REGISTRY
        .iter()
        .map(|entry| {
            let mut value = serde_json::json!({
                "id": entry.id,
                "label": entry.label,
                "category": entry.category,
            });
            if let Some(order) = entry.gallery_order {
                value["galleryOrder"] = serde_json::json!(order);
            }
            value
        })
        .collect();
    serde_json::to_string(&entries).expect("template catalog serializes")
}
